-- ── Baasha Delivery — Server Admin ───────────────────────────────────────
-- /deliveryspot recording → stops_recorded.lua (ace-checked, appended).

local JOB = 'delivery'
local Core = exports.baasha_jobcore

local function isAdmin(src)
    return IsPlayerAceAllowed(src, (Config.Admin and Config.Admin.ace) or 'command')
end

local function f(n) return ('%.2f'):format(tonumber(n) or 0) end

lib.callback.register('baasha_delivery:recordStop', function(src, data)
    if not isAdmin(src) then return false, L('admin_no_ace') end
    if type(data) ~= 'table' or type(data.door) ~= 'table' then return false, L('admin_badtype') end

    local t = data.type
    if t ~= 'house' and t ~= 'business' then t = 'house' end
    local d = data.door
    local van = data.van and ('vector3(%s, %s, %s)'):format(f(data.van.x), f(data.van.y), f(data.van.z)) or 'nil'
    local line = ('    { label = %q, door = vector4(%s, %s, %s, %s), van = %s, type = %q, area = \'recorded\' }, -- VERIFY'):format(
        data.label or ('Recorded ' .. t), f(d.x), f(d.y), f(d.z), f(d.w), van, t)

    local file = 'stops_recorded.lua'
    local existing = LoadResourceFile(GetCurrentResourceName(), file) or ''
    if existing == '' then
        existing = '-- ── Recorded delivery stops (paste into Config.Stops) ──\n-- Generated by /deliveryspot. Every coordinate: VERIFY in-game.\n'
    end
    local content = existing .. line .. '\n'
    local ok = SaveResourceFile(GetCurrentResourceName(), file, content, #content)
    if not ok then return false, 'Could not write stops_recorded.lua (is the resource unpacked / writable?)' end
    return true, L('admin_recorded', data.label or t)
end)
